import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { counterItems } from "../src/games/deadlock/counters/items.js";

// Explicit maintenance operation; the bot never fetches game data during a lookup.
const endpoint = "https://api.deadlock-api.com/v1/assets/items";
const response = await fetch(endpoint, { signal: AbortSignal.timeout(30_000) });
if (!response.ok) throw new Error(`Item catalog returned HTTP ${response.status}`);
const catalog: unknown = await response.json();
if (!Array.isArray(catalog)) throw new Error("Expected an array of items");
const result: Record<string, { id: number; className: string; name: string; sourceImage: string; file: string }> = {};
const directory = new URL("../assets/deadlock/counters/", import.meta.url);
await mkdir(directory, { recursive: true });
for (const [key, previous] of Object.entries(counterItems)) {
  const item = catalog.find((value) => value?.type === "upgrade" && value.class_name === previous.className && value.id === previous.id);
  if (!item || typeof item.name !== "string" || typeof item.shop_image !== "string") throw new Error(`Missing catalog entry: ${key}`);
  const imageUrl = new URL(item.shop_image);
  if (imageUrl.origin !== "https://assets-bucket.deadlock-api.com" || !imageUrl.pathname.endsWith(".png")) throw new Error(`Unexpected artwork URL for ${key}`);
  const artwork = await fetch(imageUrl, { signal: AbortSignal.timeout(30_000) });
  if (!artwork.ok) throw new Error(`Artwork for ${key} returned HTTP ${artwork.status}`);
  const bytes = Buffer.from(await artwork.arrayBuffer());
  if (bytes.length > 1_000_000 || !bytes.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]))) throw new Error(`Invalid PNG for ${key}`);
  await writeFile(new URL(previous.file, directory), bytes);
  result[key] = { id: item.id, className: item.class_name, name: item.name, sourceImage: imageUrl.href, file: previous.file };
}
await writeFile(new URL("../src/games/deadlock/counters/items.ts", import.meta.url),
  `// Generated by scripts/sync-deadlock-counter-assets.ts; keyed by stable guide identifiers.\nexport const counterItems = ${JSON.stringify(result, null, 2)} as const;\n\nexport type CounterItemId = keyof typeof counterItems;\n`);
await writeFile(new URL("manifest.json", directory), JSON.stringify({ source: endpoint, fetchedAt: new Date().toISOString(), items: Object.keys(result).length }, null, 2) + "\n");
console.log(`Saved ${Object.keys(result).length} counter item pictures to ${fileURLToPath(directory)}. Review the diff before committing.`);
